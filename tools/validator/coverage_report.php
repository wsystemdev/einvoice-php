<?php

/**
 * Writes docs/validator-rules.md (the php-core rule coverage list that feeds the rules matrix in the plan) from one or
 * more differential.php JSON reports:  php tools/validator/coverage_report.php report1.json [report2.json ...]
 */

declare(strict_types=1);

$rules = [];
$stats = ['cases' => 0, 'mutants' => 0, 'identical' => 0, 'differ' => 0, 'aborted_both' => 0];
$diffs = [];
foreach (array_slice($argv, 1) as $f) {
    $r = json_decode((string) file_get_contents($f), true, 512, JSON_THROW_ON_ERROR);
    foreach ($stats as $k => $_) {
        $stats[$k] += $r['stats'][$k] ?? 0;
    }
    array_push($diffs, ...$r['diffs']);
    foreach ($r['rules'] as $id => $info) {
        $rules[$id]['files'] = $info['files'];
        foreach (['saxon_fired', 'mismatch', 'not_evaluated'] as $k) {
            $rules[$id][$k] = ($rules[$id][$k] ?? 0) + ($info[$k] ?? 0);
        }
        if (isset($info['unsupported'])) {
            $rules[$id]['unsupported'] = $info['unsupported'];
        }
    }
}
ksort($rules, SORT_NATURAL);
$total = count($rules);
$unsupported = array_filter($rules, static fn ($r) => isset($r['unsupported']));
$fired = array_filter($rules, static fn ($r) => !isset($r['unsupported']) && $r['saxon_fired'] > 0);
$mism = array_filter($rules, static fn ($r) => $r['mismatch'] > 0);
$docs = $stats['cases'] + $stats['mutants'];
$md = "# php-core rule coverage (generated)\n\n"
    . "Generated by `tools/validator/coverage_report.php` from `tools/validator/differential.php` runs: php-core vs SaxonC "
    . "on the validator corpus ({$stats['cases']} documents) plus {$stats['mutants']} seeded mutations "
    . "(deleted elements, emptied/garbled values, changed amounts, dates and codes). Rule files: the bundled KoSIT XRechnung 3.0.2 "
    . "configuration 2026-08-31 (CEN EN 16931 UBL + CII, KoSIT XRechnung UBL + CII), unmodified.\n\n"
    . "php-core is a **pre-check**: it evaluates these official rule files with a pure-PHP engine. It is not the official engine, "
    . "and results always say `engine: \"php-core\"`, `conformance: \"pre-check\"`. For the complete official rule sets, "
    . "use SaxonC or the W System validator/API.\n\n"
    . "## Summary\n\n"
    . "| | |\n|---|---|\n"
    . "| Rules (assert ids) in the bundled files | {$total} |\n"
    . "| Evaluated by php-core | " . ($total - count($unsupported)) . " |\n"
    . "| Not evaluable by php-core (listed below; reported per result in `rules_not_evaluated`) | " . count($unsupported) . " |\n"
    . "| Rules that fired at least once under SaxonC in the test runs (and so were compared as failures, not only passes) | " . count($fired) . " |\n"
    . "| Documents compared | {$docs} |\n"
    . "| Identical results (same rule ids, severities, messages, locations, or both engines aborted on a type error) | {$stats['identical']} |\n"
    . "| Documents with any difference | {$stats['differ']} |\n"
    . "| Rules involved in a difference | " . count($mism) . " |\n\n";
if ($diffs) {
    $md .= "## Differences found\n\n";
    foreach ($diffs as $d) {
        $md .= '- `' . $d['doc'] . '`: SaxonC ' . implode('; ', array_map(static fn ($x) => explode('|', $x)[0], $d['missing'])) . ' / php-core ' . implode('; ', array_map(static fn ($x) => explode('|', $x)[0], $d['extra'])) . "\n";
    }
    $md .= "\n";
}
$md .= "## Rule list\n\n`fired` = number of documents where SaxonC reported the rule; php-core matched all of them unless `mismatch` > 0. "
    . "A rule with fired = 0 was evaluated on every document but only seen passing.\n\n"
    . "| Rule | Rule files | php-core | fired (SaxonC) | mismatch |\n|---|---|---|---|---|\n";
foreach ($rules as $id => $r) {
    $md .= "| {$id} | " . implode(', ', array_unique($r['files'])) . ' | ' . (isset($r['unsupported']) ? 'not evaluated: ' . $r['unsupported'] : 'evaluated')
        . " | {$r['saxon_fired']} | {$r['mismatch']} |\n";
}
file_put_contents(__DIR__ . '/../../docs/validator-rules.md', $md);
printf("rules %d, unsupported %d, fired %d, docs %d, differ %d\n", $total, count($unsupported), count($fired), $docs, $stats['differ']);
